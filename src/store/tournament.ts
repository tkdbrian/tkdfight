export type TournamentPhase = "setup" | "fighting" | "results";
export type TournamentMode = "round-robin" | "elimination" | "groups";

export interface CompetitorEntry {
  id: string;
  name: string;
  team?: string;
  weight?: number;
}

export interface TournamentGroup {
  id: string;
  competitors: CompetitorEntry[];
  size: number;
}

export interface FightEntry {
  id: string;
  red: CompetitorEntry;
  blue: CompetitorEntry;
  winner?: "red" | "blue" | "draw";
  winReason?: string;
  completed: boolean;
  // Groups / round-robin fields
  groupId?: string;
  flagsRed?: number;
  flagsBlue?: number;
  warningsRed?: number;
  warningsBlue?: number;
  foulsRed?: number;
  foulsBlue?: number;
  isTiebreakExtra?: boolean;
  /** Direct first-place playoff versus a mini round robin among 3+ tied leaders. */
  playoffKind?: "direct" | "mini";
  /** Snapshot of the fully completed regular group when this playoff was authorized. */
  playoffBasis?: string;
  tiebreakerSeconds?: number;
  isFinalFight?: boolean;
  isGoldenPointFight?: boolean;
  // Peleas reasignadas desde otro cuadrilátero (Mesa Central)
  importedFrom?: string;
  // Bracket fields
  bracketRound?: number;
  bracketPosition?: number;
  bracketMatchId?: string;
  /** Durable continuation lineage; absent only for legacy bouts. */
  continuationParentFightId?: string;
  continuationStage?: "timed-extra" | "golden-point";
}

