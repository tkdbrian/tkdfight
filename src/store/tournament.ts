const PENDING_FIGHT_PROPOSAL_PREFIX = "tkd-pending-fight-v1:";

function createCategoryId(): string {
  return globalThis.crypto.randomUUID();
}

function cloneSnapshot(snapshot: TournamentCategorySnapshot): TournamentCategorySnapshot {
  return JSON.parse(JSON.stringify(snapshot)) as TournamentCategorySnapshot;
}

function snapshotWithEventProfile(
  snapshot: TournamentCategorySnapshot,
  eventProfiles: Record<string, "yusan-2026">,
): TournamentCategorySnapshot {
  const copy = cloneSnapshot(snapshot);
  const profile = copy.config.eventId ? eventProfiles[copy.config.eventId] : undefined;
  if (profile && !copy.config.profileId) {
    copy.config.profileId = profile;
    copy.config.profileApplied = false;
  }
  return copy;
}

function isSnapshot(value: unknown, categoryId: string): value is TournamentCategorySnapshot {
  if (!value || typeof value !== "object") return false;
  const snapshot = value as Partial<TournamentCategorySnapshot>;
  return snapshot.config?.id === categoryId
    && (snapshot.phase === "setup" || snapshot.phase === "fighting" || snapshot.phase === "results")
    && Array.isArray(snapshot.competitors)
    && Array.isArray(snapshot.fights)
    && Array.isArray(snapshot.groups)
    && Array.isArray(snapshot.bracketMatches)
    && Array.isArray(snapshot.bracketSeeds)
    && Number.isInteger(snapshot.currentFightIndex)
    && typeof snapshot.setupStarted === "boolean";
}

function sanitizeCategoryRegistry(registry: TournamentCategoryRegistry): TournamentCategoryRegistry {
  for (const id of Object.keys(registry.categories)) {
    if (categoryExecutionDeleted(id)) delete registry.categories[id];
  }
  registry.visibleCategoryIds = registry.visibleCategoryIds.filter((id) => registry.categories[id] && !categoryExecutionUnavailable(id));
  if (registry.selectedCategoryId && !registry.visibleCategoryIds.includes(registry.selectedCategoryId)) {
    registry.selectedCategoryId = registry.visibleCategoryIds[0] ?? null;
  }
  if (registry.draftCategoryId && categoryExecutionUnavailable(registry.draftCategoryId)) registry.draftCategoryId = null;
  if (registry.draftReturnCategoryId && categoryExecutionUnavailable(registry.draftReturnCategoryId)) registry.draftReturnCategoryId = null;
  return registry;
}

function readCategoryRegistry(includeUnavailable = false): TournamentCategoryRegistry | null {
  try {
    if (typeof localStorage === "undefined") return null;
    const raw = localStorage.getItem(TOURNAMENT_CATEGORY_STORAGE_KEY);
    if (raw === null) {
      return {
        version: 2,
        categories: {},
        visibleCategoryIds: [],
        selectedCategoryId: null,
        draftCategoryId: null,
        draftReturnCategoryId: null,
      };
    }
    const parsed: unknown = JSON.parse(raw);
    if (!parsed || typeof parsed !== "object") return null;
    const registry = parsed as {
      version?: number;
      categories?: Record<string, TournamentCategorySnapshot>;
      visibleCategoryIds?: string[];
      selectedCategoryId?: string | null;
      draftCategoryId?: string | null;
      draftReturnCategoryId?: string | null;
      archives?: Record<string, CategoryArchiveMetadata>;
    };
    if ((registry.version !== 1 && registry.version !== 2)
      || !registry.categories
      || typeof registry.categories !== "object"
      || Array.isArray(registry.categories)) return null;
    if (Object.entries(registry.categories).some(([id, snapshot]) => !isSnapshot(snapshot, id))) return null;
    const categoryIds = Object.keys(registry.categories);
    if (registry.version === 1) {
      const migrated: TournamentCategoryRegistry = {
        version: 2,
        categories: registry.categories,
        visibleCategoryIds: categoryIds,
        selectedCategoryId: categoryIds[0] ?? null,
        draftCategoryId: null,
        draftReturnCategoryId: null,
      };
      return includeUnavailable ? migrated : sanitizeCategoryRegistry(migrated);
    }
    if (!Array.isArray(registry.visibleCategoryIds)
      || registry.visibleCategoryIds.some((id) => typeof id !== "string" || !registry.categories?.[id])
      || (registry.selectedCategoryId !== null && (typeof registry.selectedCategoryId !== "string" || !registry.categories[registry.selectedCategoryId] || !registry.visibleCategoryIds.includes(registry.selectedCategoryId)))
      || (registry.draftCategoryId !== null && (typeof registry.draftCategoryId !== "string" || !registry.categories[registry.draftCategoryId]))
      || (registry.draftReturnCategoryId !== null && (typeof registry.draftReturnCategoryId !== "string" || !registry.categories[registry.draftReturnCategoryId]))) return null;
    return includeUnavailable ? registry as TournamentCategoryRegistry : sanitizeCategoryRegistry(registry as TournamentCategoryRegistry);
  } catch {
    return null;
  }
}

function writeCategoryRegistry(registry: TournamentCategoryRegistry): boolean {
  try {
    if (typeof localStorage === "undefined") return false;
    const safe = sanitizeCategoryRegistry(registry);
    const selected = safe.selectedCategoryId ? safe.categories[safe.selectedCategoryId] : undefined;
    if (!selected) return false;
    const current = useTournamentStore.getState();
    const next = { ...current, ...snapshotWithEventProfile(selected, current.eventProfiles),
      categoryRevision: current.categoryRevision + 1 };
    safe.categories[next.config.id] = getSnapshot(next);
    return commitTournamentAuthorities(JSON.stringify({ state: next, version: 1 }), JSON.stringify(safe));
  } catch {
    return false;
  }
}

function saveSnapshot(snapshot: TournamentCategorySnapshot, mainState: TournamentState): boolean {
  const registry = readCategoryRegistry();
  if (!registry) return reportTournamentPersistenceFailure("No se puede leer el registro de categorías; no se sobrescribió ninguna copia");
  if (registry.archives?.[snapshot.config.id] || categoryRestartInteractionBlocked()
    || categoryExecutionUnavailable(snapshot.config.id)) return false;
  if (!registry.categories[snapshot.config.id]) {
    registry.visibleCategoryIds.push(snapshot.config.id);
    if (snapshot.phase === "setup" && snapshot.setupStarted && snapshot.config.requiresGradeSelection) {
      registry.draftCategoryId = snapshot.config.id;
    }
  }
  registry.categories[snapshot.config.id] = cloneSnapshot(snapshot);
  registry.selectedCategoryId = snapshot.config.id;
  if (registry.draftCategoryId === snapshot.config.id && snapshot.phase !== "setup" && snapshot.fights.length > 0) {
    registry.draftCategoryId = null;
    registry.draftReturnCategoryId = null;
  }
  return commitTournamentAuthorities(JSON.stringify({ state: mainState, version: 1 }),
    JSON.stringify(sanitizeCategoryRegistry(registry)));
}

function categoryEntries(registry: TournamentCategoryRegistry): TournamentCategoryEntry[] {
  const visibleIds = new Set(registry.visibleCategoryIds);
  return Object.entries(registry.categories).filter(([id]) => !registry.archives?.[id] && !categoryExecutionUnavailable(id)).map(([id, snapshot]) => ({
    id,
    name: snapshot.config.categoryName.trim() || "Nueva categoría",
    tournamentName: snapshot.config.tournamentName,
    matchType: snapshot.config.matchType ?? "sparring",
    mode: snapshot.config.mode ?? "round-robin",
    visible: visibleIds.has(id),
    isDraft: registry.draftCategoryId === id,
    fightIds: snapshot.fights.map((fight) => fight.id),
  }));
}

function getSnapshot(state: TournamentState): TournamentCategorySnapshot {
  return cloneSnapshot({
    phase: state.phase,
    config: state.config,
    competitors: state.competitors,
    fights: state.fights,
    groups: state.groups,
    currentFightIndex: state.currentFightIndex,
    bracketMatches: state.bracketMatches,
    bracketSeeds: state.bracketSeeds,
    setupStarted: state.setupStarted,
  });
}

